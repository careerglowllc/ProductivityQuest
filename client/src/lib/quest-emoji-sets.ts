// Combines entries by emoji so the same emoji is never listed twice and every keyword still finds it.
export function mergeEmojiEntries(...lists: EmojiEntry[][]): EmojiEntry[] {
  const merged = new Map<string, Set<string>>();
  for (const entry of lists.flat()) {
    const words = merged.get(entry.emoji) ?? new Set<string>();
    entry.keywords.forEach(word => words.add(word));
    merged.set(entry.emoji, words);
  }
  return Array.from(merged, ([emoji, words]) => ({ emoji, keywords: Array.from(words) }));
}

export const QUEST_EMOJI_ENTRIES = mergeEmojiEntries(...QUEST_EMOJI_SETS.map(set => set.entries));
